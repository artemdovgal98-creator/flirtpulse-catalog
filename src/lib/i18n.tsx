export const DICTS: Record<Lang, Dict> = { en, uk, ru, pl, de, fr, es, pt, it, tr, ar, zh };

const STORAGE_KEY = "flirtpulse_lang";

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  dir: "ltr" | "rtl";
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ru");

  useEffect(() => {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (stored && DICTS[stored]) {
        setLangState(stored);
        console.log("[i18n] restored language from storage:", stored);
      }
    } catch (err) {
      console.error("[i18n] could not read stored language:", err);
    }
  }, []);

  useEffect(() => {
    const dir = RTL_LANGS.includes(lang) ? "rtl" : "ltr";
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", dir);
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    console.log("[i18n] language switched to:", next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch (err) {
      console.error("[i18n] could not persist language:", err);
    }
    // Best-effort sync for signed-in users; never blocks the UI.
    fetch("/api/preferences", {
      method: "PUT",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ language: next }),
    }).catch((err) => console.error("[i18n] preference sync failed:", err));
  }, []);

  const value = useMemo<I18nValue>(() => {
    const dict = DICTS[lang] ?? en;
    return {
      lang,
      setLang,
      t: (key: string) => dict[key] ?? en[key] ?? key,
      dir: RTL_LANGS.includes(lang) ? "rtl" : "ltr",
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside <I18nProvider>");
  return ctx;
}
